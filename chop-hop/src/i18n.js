let lang = 'en';

export function setLang(l) {
  lang = STR[l] ? l : 'en';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

export function t(key, ...args) {
  let s = (STR[lang] && STR[lang][key]) || STR.en[key] || key;
  for (let i = 0; i < args.length; i++) s = s.replace('{' + i + '}', args[i]);
  return s;
}

